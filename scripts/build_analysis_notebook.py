"""Build and execute a dependency-light results notebook from immutable-backed logs.

Only the cells defined below are executed; existing notebook code is never read.
Outputs are standard nbformat stream outputs, viewable without plotting packages.
"""
from __future__ import annotations

import contextlib
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SECTIONS = [
    ("ReelRank: controlled comparisons", """This notebook reads measured results, not target numbers. Models use training-fitted features and standard-validation selection. The random log was inspected in previous development and is explicitly exploratory. All tables below were executed by `python scripts/build_analysis_notebook.py`.""", """
import json
from pathlib import Path
import pandas as pd
root = next(p for p in [Path.cwd(), *Path.cwd().parents] if (p / 'reelrank' / 'ranking').exists())
def load(name):
    return json.loads((root / 'results' / f'{name}.json').read_text())
print('Source root:', root)
"""),
    ("Ranking: choose on validation", """Same feature information and samples across models. LR is selected by standard-validation long-view GAUC. DeepFM has the best validation long-view log loss; MMoE is retained as an experiment. These are single-seed results, not evidence that one architecture universally wins.""", """
rows = []
for model in ['lr', 'deepfm', 'mmoe']:
    for suffix in ['_validation', '']:
        record = load(f'ranking_{model}{suffix}')
        m = record['metrics']['long_view']
        rows.append({'model': model, 'split': record['config']['evaluation_split'], **m})
print(pd.DataFrame(rows).to_string(index=False))
print('MMoE validation learning curve:')
print(pd.DataFrame(load('ranking_mmoe_validation')['extra']['training_history']).to_string(index=False))
"""),
    ("Retrieval on matched users", """All methods use long-view relevance, the same seed-42 2,000-user cohort and allow repeats. Earlier results used different cohorts and policies, so before/after changes cannot be attributed to one fix.""", """
rows = []
for method in ['popularity', 'itemcf', 'two_tower']:
    record = load(f'retrieval_{method}')
    rows.append({'method': method, **record['metrics']})
print(pd.DataFrame(rows).to_string(index=False))
"""),
    ("Cascade and uncertainty", """Both candidate generators receive the same safety policy. Full-pool NDCG is overlap with sparse observed positives, not an estimate of online benefit. Paired bootstrap intervals quantify user variation only. An interval crossing zero does not establish a positive effect.""", """
rows = []
for model in ['lr', 'mmoe']:
    for safety in ['no_safety', 'with_safety']:
        r = load(f'e2e_{model}_{safety}')
        m = r['metrics']; ci = m['paired_bootstrap']
        rows.append({'ranker': model, 'safety': safety, 'users': m['n_users'],
                     'two_tower_ndcg': m['ndcg@10_two_tower'], 'popularity_ndcg': m['ndcg@10_popularity'],
                     'relative_lift': m.get('lift_vs_pop'), 'difference': ci['mean_difference'],
                     'difference_ci95': ci['difference_ci95'],
                     'two_tower_hit_users': m['users_with_positive_hit_two_tower'],
                     'popularity_hit_users': m['users_with_positive_hit_popularity']})
print(pd.DataFrame(rows).to_string(index=False))
"""),
    ("Index choice", """Choose based on this measured candidate-pool size. Timing noise and hardware matter; these index benchmarks are not end-to-end request latency.""", """
a = load('retrieval_faiss')['metrics']
print(pd.DataFrame([{'index': key, **a[key]} for key in ['flat', 'hnsw']]).to_string(index=False))
print('HNSW recall vs exact:', a['hnsw_recall_vs_flat'])
"""),
    ("Safety limitations", """Caption-only weak-label evaluation. All-safe human review cannot establish unsafe recall. The uncertain-band count is hypothetical routing, not measured LLM serving. Existing labels were not regenerated by the correctness fixes.""", """
for name in ['safety_classifier', 'safety_human_kappa']:
    print(name, json.dumps(load(name)['metrics'], indent=2))
"""),
    ("Serving and reproducibility", """Measured achieved throughput includes Locust think time. The source snapshot and hashes identify the implementation and artifacts; per-user cascade records permit independent uncertainty checks. No online experiment or production-scale claim is made.""", """
print(json.dumps(load('serving_loadtest')['metrics'], indent=2))
for name in ['ranking_lr', 'retrieval_two_tower', 'e2e_lr_with_safety', 'serving_loadtest']:
    r = load(name)
    print(name, 'record:', r.get('record_path'), 'source:', r.get('provenance', {}).get('source_hash'))
"""),
]


def main():
    import os
    os.chdir(ROOT)
    cells, namespace = [], {}
    for index, (title, explanation, source) in enumerate(SECTIONS, 1):
        cells.append({'id': f'text-{index}', 'cell_type': 'markdown', 'metadata': {},
                      'source': f'## {title}\n\n{explanation}'.splitlines(keepends=True)})
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            exec(compile(source, f'analysis-cell-{index}', 'exec'), namespace)
        cells.append({'id': f'code-{index}', 'cell_type': 'code', 'metadata': {},
                      'source': source.strip().splitlines(keepends=True), 'execution_count': index,
                      'outputs': [{'output_type': 'stream', 'name': 'stdout', 'text': output.getvalue().splitlines(keepends=True)}]})
    notebook = {'nbformat': 4, 'nbformat_minor': 5, 'cells': cells,
                'metadata': {'kernelspec': {'display_name': 'Python 3', 'language': 'python', 'name': 'python3'},
                             'language_info': {'name': 'python'}}}
    destination = ROOT / 'notebooks' / 'analysis.ipynb'
    destination.parent.mkdir(exist_ok=True)
    destination.write_text(json.dumps(notebook, indent=1))
    print(f'Executed {len(SECTIONS)} cells: {destination}')


if __name__ == '__main__':
    main()
